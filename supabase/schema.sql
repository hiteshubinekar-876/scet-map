create table if not exists public.floors (
  id integer primary key,
  name text not null,
  map_url text,
  notes text
);
create table if not exists public.nodes (
  id text primary key,
  floor_id integer not null references public.floors(id),
  name text not null,
  x numeric not null,
  y numeric not null,
  type text not null check (type in ('gate','junction','room','stairs','lift','office','lab','restroom')),
  accessible boolean not null default true
);
create table if not exists public.edges (
  id bigint generated by default as identity primary key,
  a text not null references public.nodes(id) on delete cascade,
  b text not null references public.nodes(id) on delete cascade,
  distance_m numeric not null check (distance_m > 0),
  type text not null check (type in ('walk','stairs','lift')),
  accessible boolean not null default true,
  directed boolean not null default false,
  check (a <> b)
);
create table if not exists public.places (
  id bigint generated by default as identity primary key,
  node_id text not null references public.nodes(id) on delete cascade,
  name text not null,
  aliases text[] not null default '{}',
  department text,
  category text not null default 'classroom' check (category in ('classroom','lab','office','restroom','facility'))
);
-- Navigation reads can be public for a public campus directory; do not enable writes for anon users.
alter table public.floors enable row level security;
alter table public.nodes enable row level security;
alter table public.edges enable row level security;
alter table public.places enable row level security;
create policy "public can read floors" on public.floors for select to anon, authenticated using (true);
create policy "public can read nodes" on public.nodes for select to anon, authenticated using (true);
create policy "public can read edges" on public.edges for select to anon, authenticated using (true);
create policy "public can read places" on public.places for select to anon, authenticated using (true);
