-- 1. Floors table: represents physical building levels
create table if not exists public.floors (
  id integer primary key,
  name text not null,
  map_url text,
  notes text,
  created_at timestamptz not null default now()
);

-- 2. Nodes table: permanent spatial checkpoints, rooms, junctions, stairs, lifts
create table if not exists public.nodes (
  id text primary key,
  floor_id integer not null references public.floors(id) on delete restrict,
  name text not null,
  x numeric not null,
  y numeric not null,
  type text not null check (type in ('gate', 'junction', 'room', 'stairs', 'lift', 'office', 'lab', 'restroom')),
  accessible boolean not null default true,
  description text,
  created_at timestamptz not null default now()
);

-- 3. Edges table: physical walkable connections between two nodes
create table if not exists public.edges (
  id bigint generated by default as identity primary key,
  a text not null references public.nodes(id) on delete cascade,
  b text not null references public.nodes(id) on delete cascade,
  distance_m numeric not null check (distance_m > 0),
  type text not null check (type in ('walk', 'stairs', 'lift')),
  accessible boolean not null default true,
  directed boolean not null default false,
  check (a <> b),
  created_at timestamptz not null default now()
);

-- 4. Places table: searchable directory titles, aliases, departments mapped to nodes
create table if not exists public.places (
  id bigint generated by default as identity primary key,
  node_id text not null references public.nodes(id) on delete cascade,
  name text not null,
  aliases text[] not null default '{}',
  department text,
  category text not null default 'classroom' check (category in ('classroom', 'lab', 'office', 'restroom', 'facility')),
  created_at timestamptz not null default now()
);

-- ========================================================================
-- Performance & Graph Traversal Indexes
-- ========================================================================
create index if not exists idx_nodes_floor_id on public.nodes(floor_id);
create index if not exists idx_nodes_type on public.nodes(type);
create index if not exists idx_edges_a on public.edges(a);
create index if not exists idx_edges_b on public.edges(b);
create index if not exists idx_edges_type_accessible on public.edges(type, accessible);
create index if not exists idx_places_node_id on public.places(node_id);
create index if not exists idx_places_category on public.places(category);

-- ========================================================================
-- Row Level Security (RLS) Policies
-- Public read-only access for navigation; authenticated admin writes only
-- ========================================================================
alter table public.floors enable row level security;
alter table public.nodes enable row level security;
alter table public.edges enable row level security;
alter table public.places enable row level security;

-- Public read policies (anon & authenticated)
create policy "public_read_floors" on public.floors
  for select to anon, authenticated using (true);

create policy "public_read_nodes" on public.nodes
  for select to anon, authenticated using (true);

create policy "public_read_edges" on public.edges
  for select to anon, authenticated using (true);

create policy "public_read_places" on public.places
  for select to anon, authenticated using (true);

-- Authenticated administrative policies (writes restricted to authenticated staff)
create policy "admin_insert_floors" on public.floors
  for insert to authenticated with check (true);

create policy "admin_update_floors" on public.floors
  for update to authenticated using (true);

create policy "admin_delete_floors" on public.floors
  for delete to authenticated using (true);

create policy "admin_insert_nodes" on public.nodes
  for insert to authenticated with check (true);

create policy "admin_update_nodes" on public.nodes
  for update to authenticated using (true);

create policy "admin_delete_nodes" on public.nodes
  for delete to authenticated using (true);

create policy "admin_insert_edges" on public.edges
  for insert to authenticated with check (true);

create policy "admin_update_edges" on public.edges
  for update to authenticated using (true);

create policy "admin_delete_edges" on public.edges
  for delete to authenticated using (true);

create policy "admin_insert_places" on public.places
  for insert to authenticated with check (true);

create policy "admin_update_places" on public.places
  for update to authenticated using (true);

create policy "admin_delete_places" on public.places
